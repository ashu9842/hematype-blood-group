import type { PredictionResult } from "./predict";

export function exportReport(
  result: PredictionResult,
  files: { fingerprint: string | null; smear: string | null },
) {
  const now = new Date();
  const id = `HGX-${now.getFullYear()}${(now.getMonth() + 1)
    .toString()
    .padStart(2, "0")}${now.getDate().toString().padStart(2, "0")}-${
    crypto.randomUUID().slice(0, 8).toUpperCase()
  }`;

  const rows = result.distribution
    .map(
      (d, i) => `
      <tr style="${i === 0 ? "font-weight:700;color:#e11d3a;" : ""}">
        <th scope="row" style="font-weight:inherit;text-align:left;">${d.group}</th>
        <td>${(d.probability * 100).toFixed(2)}%</td>
      </tr>`,
    )
    .join("");

  const img = (src: string | null, cap: string) =>
    src
      ? `<figure><img src="${src}" /><figcaption>${cap}</figcaption></figure>`
      : "";

  const html = `<!doctype html><html><head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width,initial-scale=1">
  <title>Blood Group Estimation Report — ${id}</title>
  <style>
    * { font-family: -apple-system, Arial, sans-serif; }
    body { margin: 40px; color: #12151b; }
    h1 { font-size: 20px; letter-spacing: 1px; margin: 0; }
    .sub { color: #6b7280; font-size: 12px; margin-top: 4px; }
    .rule { border: none; border-top: 2px solid #e11d3a; margin: 16px 0; }
    .grid { display: flex; gap: 32px; margin: 20px 0; flex-wrap: wrap; }
    .big { font-size: 64px; font-weight: 800; color: #e11d3a; line-height: 1; }
    table { border-collapse: collapse; width: 260px; font-size: 13px; }
    th, td { border-bottom: 1px solid #e5e7eb; padding: 6px 4px; text-align: left; }
    figure { margin: 0; }
    img { width: 150px; height: 150px; object-fit: cover; border: 1px solid #e5e7eb; }
    figcaption { font-size: 10px; color: #6b7280; margin-top: 4px; }
    .disc { background: #fef2f2; border: 1px solid #fecaca; color: #991b1b;
      font-size: 11px; padding: 12px; margin-top: 28px; line-height: 1.5; }
    .meta { font-size: 11px; color: #6b7280; margin-top: 8px; }
    .print-btn { display: block; margin: 20px 0 0; padding: 10px 20px;
      background: #e11d3a; color: #fff; border: none; font-size: 13px;
      font-weight: 700; letter-spacing: 1px; cursor: pointer; }
    @media print { .print-btn { display: none; } }
  </style>
  </head><body>
  <h1>BLOOD GROUP ESTIMATION REPORT</h1>
  <div class="sub">Multi-modal ensemble · Report ${id} · ${now.toLocaleString()}</div>
  <hr class="rule" />
  <div class="grid">
    <div>
      <div style="font-size:11px;color:#6b7280;">PREDICTED PHENOTYPE</div>
      <div class="big">${result.top}</div>
      <div class="meta">Confidence: ${(result.confidence * 100).toFixed(1)}%<br/>
      Fingerprint stream: ${(result.modality.fingerprint * 100).toFixed(1)}% ·
      Smear stream: ${(result.modality.smear * 100).toFixed(1)}%<br/>
      Source: ${result.source} · Latency: ${result.latencyMs}ms</div>
    </div>
    <table>
      <thead><tr><th scope="col">CLASS</th><th scope="col">PROBABILITY</th></tr></thead>
      <tbody>${rows}</tbody>
    </table>
  </div>
  <div class="grid">
    ${img(files.fingerprint, "Input A — Fingerprint biometric")}
    ${img(files.smear, "Input B — Microscopic blood smear")}
  </div>
  <div class="disc">
    <strong>NOT A MEDICAL DEVICE.</strong> This report is generated by an
    experimental research prototype. Blood-group inference from fingerprint
    biometrics has no established scientific or clinical validity. Results must
    never be used for transfusion, cross-matching, diagnosis, or any medical
    decision. Blood typing must always be performed by an accredited laboratory
    using serological methods.
  </div>
  <button class="print-btn" onclick="window.print()">PRINT / SAVE AS PDF</button>
  </body></html>`;

  const blob = new Blob([html], { type: "text/html" });
  const url = URL.createObjectURL(blob);
  const w = window.open(url, "_blank");
  if (!w) {
    const a = document.createElement("a");
    a.href = url;
    a.download = `hematype-report-${id}.html`;
    a.click();
  }
  setTimeout(() => URL.revokeObjectURL(url), 60_000);
}